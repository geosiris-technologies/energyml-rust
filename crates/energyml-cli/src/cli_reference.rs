//! `energyml cli-reference` - the reference of every command, written from the
//! command definitions themselves.
//!
//! The reference is generated so that nobody has to remember to write it: a
//! script runs it and fails when the committed file is stale. It is made from a
//! build with the HDF5 and PNG options, so that their flags appear in it.
//!
//! **Not by reading `--help`'s output**: that text depends on the terminal (its
//! width, its colours). The help is rendered by `clap` from the same
//! definitions, at a fixed width, so two machines write the same bytes - which
//! is what lets `--check` fail on a stale file and on nothing else.
//!
//! **What is left out, and why.** `translate` is a separate private program,
//! not a command of this tree, and a command of that name would still never be
//! written here, whatever the build. A hidden
//! command (this one) is left out like any hidden thing.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use anyhow::{Context, Result, bail};
use clap::{CommandFactory, Parser};

/// The width the help is wrapped at: fixed, so the file does not depend on the terminal that wrote it.
const WIDTH: usize = 100;

/// Commands never written into the reference, whatever the build.
const PRIVATE: &[&str] = &["translate"];

/// Where the reference is written when `--out` is not given, from the working
/// directory. A tree that keeps its documents elsewhere passes `--out`
/// (the public repository: `docs/cli-reference.md`).
pub const DEFAULT_OUT: &str = "cli-reference.md";

/// Write the reference of every command - or, with `--check`, say whether the
/// file written is still what the commands say.
#[derive(Parser)]
pub struct CliReferenceArgs {
    /// The file to write (or to check).
    #[arg(long, default_value = DEFAULT_OUT)]
    pub out: PathBuf,
    /// Do not write: fail when the file differs from what the commands say.
    #[arg(long)]
    pub check: bool,
}

/// The features this build was made with, said in the reference so a reader
/// knows which options are there.
fn features() -> Vec<&'static str> {
    let mut out = Vec::new();
    if cfg!(feature = "hdf5") {
        out.push("hdf5");
    }
    if cfg!(feature = "png") {
        out.push("png");
    }
    out
}

/// The reference, as Markdown: one section per visible command, nested ones
/// included, each its long help in a text block.
pub fn render(mut root: clap::Command) -> String {
    root = root.term_width(WIDTH).max_term_width(WIDTH);
    root.build();
    let mut out = String::new();
    let _ = writeln!(out, "# `energyml` - command reference");
    let _ = writeln!(out);
    let _ = writeln!(
        out,
        "<!-- Generated by `energyml cli-reference` from the command definitions; do not edit by hand. \
         `energyml cli-reference --out <file>` writes it, `--check` fails when it is stale. -->"
    );
    let _ = writeln!(out);
    let features = features();
    let _ = writeln!(
        out,
        "Built with the features: {}. How each command is used, with examples, is in [`cli.md`](cli.md); this page is \
         every option of every command, as `--help` prints it.",
        if features.is_empty() {
            "none".to_string()
        } else {
            features
                .iter()
                .map(|f| format!("`{f}`"))
                .collect::<Vec<_>>()
                .join(", ")
        }
    );
    let _ = writeln!(out);

    // The table of contents first: every command, with its one-line about.
    let mut sections: Vec<(String, String)> = Vec::new();
    collect(&mut root, &mut Vec::new(), &mut sections);
    let _ = writeln!(out, "## Commands");
    let _ = writeln!(out);
    let mut about = |cmd: &clap::Command, path: &str| {
        let line = cmd.get_about().map(|text| text.to_string()).unwrap_or_default();
        let _ = writeln!(
            out,
            "- [`energyml {path}`](#{}) - {}",
            anchor(path),
            line.lines().next().unwrap_or("")
        );
    };
    walk(&root, &mut Vec::new(), &mut about);
    let _ = writeln!(out);

    // The global options once, from the root's own help.
    let _ = writeln!(out, "## `energyml`");
    let _ = writeln!(out);
    let _ = writeln!(
        out,
        "```text\n{}\n```",
        root.render_long_help().to_string().trim_end()
    );
    let _ = writeln!(out);

    for (path, help) in sections {
        let _ = writeln!(out, "## `energyml {path}`");
        let _ = writeln!(out);
        let _ = writeln!(out, "```text\n{}\n```", help.trim_end());
        let _ = writeln!(out);
    }
    out
}

/// Whether a command is written into the reference.
fn shown(cmd: &clap::Command) -> bool {
    !cmd.is_hide_set() && !PRIVATE.contains(&cmd.get_name())
}

/// Every visible command under `cmd`, depth first, with its long help.
fn collect(cmd: &mut clap::Command, path: &mut Vec<String>, out: &mut Vec<(String, String)>) {
    for sub in cmd.get_subcommands_mut() {
        if !shown(sub) || sub.get_name() == "help" {
            continue;
        }
        path.push(sub.get_name().to_string());
        out.push((path.join(" "), sub.render_long_help().to_string()));
        collect(sub, path, out);
        path.pop();
    }
}

/// The same walk, for the table of contents.
fn walk(cmd: &clap::Command, path: &mut Vec<String>, visit: &mut dyn FnMut(&clap::Command, &str)) {
    for sub in cmd.get_subcommands() {
        if !shown(sub) || sub.get_name() == "help" {
            continue;
        }
        path.push(sub.get_name().to_string());
        visit(sub, &path.join(" "));
        walk(sub, path, visit);
        path.pop();
    }
}

/// The anchor GitHub and GitLab give a heading `` `energyml list` ``.
fn anchor(path: &str) -> String {
    format!("energyml-{}", path.replace(' ', "-"))
}

/// Write the reference, or check it.
pub fn run<C: CommandFactory>(args: CliReferenceArgs) -> Result<std::process::ExitCode> {
    let wanted = render(C::command());
    if args.check {
        let held = std::fs::read_to_string(&args.out)
            .unwrap_or_default()
            .replace("\r\n", "\n");
        if held == wanted {
            println!("{} is up to date", args.out.display());
            return Ok(std::process::ExitCode::SUCCESS);
        }
        bail!(
            "{path} is stale: the commands say something else. Regenerate it with `energyml cli-reference --out {path}` and commit the file.",
            path = args.out.display()
        );
    }
    write(&args.out, &wanted)?;
    println!("wrote {}", args.out.display());
    Ok(std::process::ExitCode::SUCCESS)
}

fn write(path: &Path, text: &str) -> Result<()> {
    if let Some(parent) = path.parent().filter(|p| !p.as_os_str().is_empty()) {
        std::fs::create_dir_all(parent).with_context(|| format!("creating {}", parent.display()))?;
    }
    std::fs::write(path, text).with_context(|| format!("writing {}", path.display()))
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Every visible command of the build has its section, the private one never
    /// does, and two renderings are the same bytes - what `--check` relies on.
    #[test]
    fn the_reference_names_every_visible_command_and_never_the_private_one() {
        let root = crate::Cli::command();
        let text = render(root.clone());
        let mut names = Vec::new();
        for sub in root.get_subcommands() {
            if !sub.is_hide_set() && sub.get_name() != "help" && !PRIVATE.contains(&sub.get_name()) {
                names.push(sub.get_name().to_string());
            }
        }
        assert!(names.len() > 20, "the CLI has its commands: {names:?}");
        for name in &names {
            assert!(
                text.contains(&format!("## `energyml {name}`")),
                "`{name}` has its section"
            );
        }
        assert!(
            !text.contains("## `energyml translate`"),
            "the private command is never written"
        );
        assert!(
            !text.contains("## `energyml cli-reference`"),
            "a hidden command is not written"
        );
        assert_eq!(text, render(crate::Cli::command()), "the same bytes twice");
    }
}
