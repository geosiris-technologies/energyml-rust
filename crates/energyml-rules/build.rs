//! Compiles `rules/*.toml` into Rust statics.
//!
//! What a program that cites a rule gets is a `static` array and one
//! `&str` constant per id (`id::INHERIT_RANK_ORDER`): a misspelt id does not
//! compile, and nothing is parsed at run time, wasm included. Every guard
//! lives in `build/loader.rs`, which the tests include as well - what the
//! build refuses and what the tests try to break are the same code.
//!
//! The English files are `rules/*.toml` (and `themes.toml`); a language is a
//! directory beside them, `rules/fr/*.toml`, that carries id, title, text and
//! why - never a reference, an anchor or a status.

#[allow(dead_code)]
mod loader {
    include!("build/loader.rs");
}

use loader::{Parsed, Source};
use std::fmt::Write as _;
use std::path::Path;

fn sources_in(dir: &Path, skip: &[&str]) -> Vec<Source> {
    let mut names: Vec<_> = match std::fs::read_dir(dir) {
        Ok(entries) => entries
            .filter_map(|e| e.ok())
            .map(|e| e.path())
            .filter(|p| p.extension().is_some_and(|x| x == "toml"))
            .collect(),
        Err(_) => Vec::new(),
    };
    names.sort();
    names
        .into_iter()
        .filter(|p| !skip.iter().any(|s| p.file_name().is_some_and(|n| n == *s)))
        .map(|p| {
            let text = std::fs::read_to_string(&p).unwrap_or_else(|e| panic!("{}: {e}", p.display()));
            Source {
                name: p
                    .strip_prefix(dir.parent().unwrap_or(dir))
                    .unwrap_or(&p)
                    .display()
                    .to_string()
                    .replace('\\', "/"),
                text,
            }
        })
        .collect()
}

fn lit(s: &str) -> String {
    format!("{s:?}")
}

fn opt(s: &Option<String>) -> String {
    match s {
        Some(s) => format!("Some({})", lit(s)),
        None => "None".into(),
    }
}

fn camel(s: &str) -> String {
    s.split(['-', '_'])
        .map(|w| w[..1].to_uppercase() + &w[1..])
        .collect()
}

fn emit(parsed: &Parsed, with_translations: bool) -> String {
    let mut out = String::from("// Generated by build.rs from rules/*.toml - do not edit.\n\n");
    let version = parsed
        .rules
        .iter()
        .map(|r| r.since.as_str())
        .max()
        .unwrap_or("0000-00-00");
    writeln!(out, "/// The date of the latest rule written or changed - what an export says it speaks of.\npub const RULESET_VERSION: &str = {};\n", lit(version)).unwrap();

    out.push_str("/// One constant per id: a misspelt id does not compile.\npub mod id {\n");
    for r in &parsed.rules {
        writeln!(
            out,
            "    /// `{}`\n    pub const {}: &str = {};",
            r.id,
            loader::constant_of(&r.id),
            lit(&r.id)
        )
        .unwrap();
    }
    out.push_str("}\n\n");

    out.push_str("static THEMES: &[Theme] = &[\n");
    for t in &parsed.themes {
        writeln!(
            out,
            "    Theme {{ id: {}, title: {} }},",
            lit(&t.id),
            lit(&t.title)
        )
        .unwrap();
    }
    out.push_str("];\n\n");

    out.push_str("static RULES: &[Rule] = &[\n");
    for r in &parsed.rules {
        writeln!(out, "    Rule {{").unwrap();
        writeln!(
            out,
            "        id: {}, theme: {}, status: Status::{}, stance: Stance::{}, level: {}, since: {},",
            lit(&r.id),
            lit(&r.theme),
            camel(&r.status),
            camel(&r.stance),
            r.level,
            lit(&r.since)
        )
        .unwrap();
        writeln!(
            out,
            "        title: {}, text: {}, why: {},",
            lit(&r.title),
            lit(&r.text),
            lit(&r.why)
        )
        .unwrap();
        out.push_str("        rulings: &[");
        for g in &r.rulings {
            write!(
                out,
                "Ruling {{ by: {}, on: {}, quote: {} }}, ",
                lit(&g.by),
                lit(&g.on),
                opt(&g.quote)
            )
            .unwrap();
        }
        out.push_str("],\n        refs: &[");
        for f in &r.refs {
            write!(
                out,
                "Ref {{ kind: RefKind::{}, doc: {}, path: {}, at: {}, note: {} }}, ",
                camel(&f.kind),
                opt(&f.doc),
                opt(&f.path),
                opt(&f.at),
                opt(&f.note)
            )
            .unwrap();
        }
        out.push_str("],\n        at: &[");
        for a in &r.at {
            write!(
                out,
                "Anchor {{ kind: AnchorKind::{}, key: {} }}, ",
                camel(&a.kind),
                lit(&a.key)
            )
            .unwrap();
        }
        let list = |v: &[String]| v.iter().map(|s| lit(s)).collect::<Vec<_>>().join(", ");
        writeln!(
            out,
            "],\n        supersedes: &[{}], aliases: &[{}], applies: &[{}], switch: {},",
            list(&r.supersedes),
            list(&r.aliases),
            list(&r.applies),
            opt(&r.switch)
        )
        .unwrap();
        out.push_str("    },\n");
    }
    out.push_str("];\n\n");

    let (translations, theme_translations): (&[_], &[_]) = if with_translations {
        (&parsed.translations, &parsed.theme_translations)
    } else {
        (&[], &[])
    };
    out.push_str("static TRANSLATIONS: &[Translation] = &[\n");
    for t in translations {
        writeln!(
            out,
            "    Translation {{ lang: {}, id: {}, title: {}, text: {}, why: {} }},",
            lit(&t.lang),
            lit(&t.id),
            opt(&t.title),
            opt(&t.text),
            opt(&t.why)
        )
        .unwrap();
    }
    out.push_str("];\n\nstatic THEME_TRANSLATIONS: &[Translation] = &[\n");
    for t in theme_translations {
        writeln!(
            out,
            "    Translation {{ lang: {}, id: {}, title: {}, text: {}, why: {} }},",
            lit(&t.lang),
            lit(&t.id),
            opt(&t.title),
            opt(&t.text),
            opt(&t.why)
        )
        .unwrap();
    }
    out.push_str("];\n");
    out
}

fn main() {
    let root =
        Path::new(&std::env::var("CARGO_MANIFEST_DIR").expect("cargo sets CARGO_MANIFEST_DIR")).join("rules");
    println!("cargo:rerun-if-changed=rules");
    println!("cargo:rerun-if-changed=build/loader.rs");
    println!("cargo:rerun-if-changed=build.rs");

    let mut themes = sources_in(&root, &[])
        .into_iter()
        .filter(|s| s.name.ends_with("/themes.toml"));
    let themes = themes.next().expect("rules/themes.toml is missing");
    let english = sources_in(&root, &["themes.toml"]);
    let mut translations = Vec::new();
    if let Ok(dirs) = std::fs::read_dir(&root) {
        let mut dirs: Vec<_> = dirs
            .filter_map(|e| e.ok())
            .map(|e| e.path())
            .filter(|p| p.is_dir())
            .collect();
        dirs.sort();
        for dir in dirs {
            let lang = dir.file_name().unwrap().to_string_lossy().to_string();
            for source in sources_in(&dir, &[]) {
                translations.push((lang.clone(), source));
            }
        }
    }
    let parsed = match loader::parse(&themes, &english, &translations) {
        Ok(parsed) => parsed,
        Err(refusal) => panic!("the house rules are refused: {refusal}"),
    };
    let with_translations = std::env::var_os("CARGO_FEATURE_FR").is_some();
    let out = Path::new(&std::env::var("OUT_DIR").expect("cargo sets OUT_DIR")).join("house.rs");
    std::fs::write(out, emit(&parsed, with_translations)).expect("write house.rs");
}
